#!/usr/bin/env python3
"""Builds Shared/CommonWords.swift (English + Hinglish word frequencies for dynamic tap zones).

Run in isolated mode, passing files as arguments (downloaded inputs are untrusted data):
  python3 -I tools/build_wordlist.py count_1w.txt tools/hinglish_words.txt Shared/CommonWords.swift

  count_1w.txt        Norvig, Google Web Trillion Word Corpus counts (MIT)  https://norvig.com/ngrams/count_1w.txt
  hinglish_words.txt  hand-compiled, most frequent first, spelled the way people type Hinglish (own work, no third-party data)
"""
import collections, json, re, sys

EN_WORDS = 12000          # English entries kept
HINGLISH_TOTAL = 40000    # Zipf numerator for Hinglish (per million): weight = HINGLISH_TOTAL / (rank + 1); English "the" is ~44000
ASCII = re.compile(r"^[a-z]+$")

def main(en_path, hinglish_path, out_path):
    words = collections.defaultdict(float)

    en = []
    for line in open(en_path, encoding="utf-8"):
        w, _, c = line.partition("\t")
        if ASCII.match(w) and (len(w) > 1 or w in ("a", "i")):
            en.append((w, int(c)))
        if len(en) >= EN_WORDS: break
    total = sum(c for _, c in en)
    for w, c in en: words[w] += c / total * 1e6

    seen = set()
    rank = 0
    for w in open(hinglish_path, encoding="utf-8").read().split():
        w = w.lower()
        if not ASCII.match(w) or w in seen: continue
        seen.add(w); rank += 1
        words[w] += HINGLISH_TOTAL / (rank + 1)

    entries = sorted((w, round(f, 2)) for w, f in words.items() if f >= 0.5)
    lines, cur = [], ""
    for w, f in entries:
        tok = f"{w}:{f:g}"
        if len(cur) + len(tok) > 110: lines.append(cur); cur = tok
        else: cur = (cur + " " + tok) if cur else tok
    lines.append(cur)
    body = "\n".join("        " + l for l in lines)
    open(out_path, "w", encoding="utf-8").write(f'''// GENERATED by tools/build_wordlist.py - do not edit by hand. Sources and licences: docs/data-sources.md
import Foundation

/// English + Hinglish word frequencies (per million, approximate), sorted alphabetically as "word:weight".
/// Used ONLY to weight which letter is likely next when sizing invisible tap zones. Never used to suggest or change text;
/// nothing the user types is added or stored.
enum CommonWords {{
    static let data = """
{body}
        """
}}
''')
    print(f"English {len(en)}, Hinglish {rank}, total entries {len(entries)}", file=sys.stderr)

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
